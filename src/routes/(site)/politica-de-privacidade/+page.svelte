			<h2><span class="pp-num" aria-hidden="true">01 —</span> Responsável pelo tratamento</h2>
			<p>O responsável pelo tratamento dos dados pessoais é:</p>
			<p><strong>Nostos</strong></p>
			<p>Para questões relacionadas com privacidade e proteção de dados:</p>
			<p>
				<strong>Email:</strong>
