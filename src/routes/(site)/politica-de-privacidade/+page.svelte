			</p>
		</section>

		<!-- 2 -->
		<section id="dados" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">02 —</span> Que dados recolhemos</h2>
			<p>Dependendo da utilização do website e dos serviços da Nostos, podemos recolher:</p>

			<h3>Dados de contacto</h3>
			<ul>
				<li>Nome</li>
				<li>Endereço de email</li>
				<li>Número de telefone</li>
				<li>Instagram ou outro contacto fornecido voluntariamente</li>
			</ul>

			<h3>Pedidos de serviço</h3>
			<p>Quando submetes um pedido de serviço, podemos recolher:</p>
			<ul>
				<li>Serviço pretendido</li>
				<li>Data pretendida</li>
				<li>Localização</li>
				<li>Orçamento aproximado</li>
				<li>Informações fornecidas durante o onboarding</li>
				<li>Referências ou ficheiros enviados</li>
				<li>Informação adicional fornecida voluntariamente</li>
			</ul>

			<h3>Clientes e álbuns</h3>
			<p>Para prestação dos nossos serviços, podemos tratar:</p>
			<ul>
				<li>Dados de identificação e contacto</li>
				<li>Fotografias</li>
				<li>Favoritos</li>
				<li>Informações relacionadas com álbuns</li>
				<li>Histórico de compras</li>
				<li>Informações necessárias para disponibilizar fotografias</li>
			</ul>

			<h3>Compras</h3>
			<p>Quando realizas uma compra, podemos tratar:</p>
			<ul>
				<li>Identificação do cliente</li>
				<li>Álbum associado</li>
				<li>Fotografias adquiridas</li>
				<li>Tipo de compra</li>
				<li>Valor</li>
				<li>Data da compra</li>
				<li>Estado da compra</li>
			</ul>
			<p class="pp-note">
				Os dados de pagamento necessários para processar uma transação podem ser tratados diretamente
				pelo respetivo fornecedor de pagamentos, quando aplicável. A Nostos não pretende armazenar
				dados completos de cartões de pagamento.
			</p>

			<h3>Utilização do website</h3>
			<p>
				Podemos recolher determinados dados técnicos e de utilização necessários para segurança,
				funcionamento e métricas da plataforma, tais como:
			</p>
			<ul>
				<li>Data e hora de acesso</li>
				<li>Página ou recurso acedido</li>
				<li>Informações técnicas do navegador</li>
				<li>Dados necessários para segurança da plataforma</li>
				<li>Eventos de utilização pseudonimizados ou agregados</li>
			</ul>
		</section>

		<!-- 3 -->
		<section id="finalidades" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">03 —</span> Para que utilizamos os dados</h2>
			<p>Os dados pessoais podem ser utilizados para:</p>
			<ul>
				<li>Responder a contactos e pedidos de informação</li>
				<li>Avaliar e gerir pedidos de serviço</li>
				<li>Comunicar contigo relativamente a um serviço</li>
				<li>Prestar os serviços solicitados</li>
				<li>Criar e gerir álbuns privados</li>
				<li>Disponibilizar fotografias</li>
				<li>Processar compras</li>
				<li>Gerir favoritos e preferências dentro dos álbuns</li>
				<li>Garantir a segurança da plataforma</li>
				<li>Detetar e prevenir utilização abusiva ou fraudulenta</li>
				<li>Melhorar o funcionamento do website</li>
				<li>Produzir métricas agregadas sobre utilização</li>
				<li>Cumprir obrigações legais</li>
			</ul>
			<p class="pp-note">
				Os dados não serão utilizados para finalidades incompatíveis com aquelas para as quais foram
				recolhidos.
			</p>
		</section>

		<!-- 4 -->
		<section id="base-legal" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">04 —</span> Base legal</h2>
			<p>
				Dependendo da finalidade, o tratamento pode basear-se em diferentes fundamentos previstos no
				RGPD. Entre eles:
			</p>
			<ul>
				<li>
					<strong>Execução de contrato</strong> — quando o tratamento é necessário para prestar um serviço
					solicitado.
				</li>
				<li>
					<strong>Consentimento</strong> — quando este for necessário e tiver sido solicitado de forma válida.
				</li>
				<li>
					<strong>Obrigação legal</strong> — quando a conservação ou utilização dos dados for exigida por
					lei.
				</li>
				<li>
					<strong>Interesse legítimo</strong> — quando aplicável, nomeadamente para segurança, prevenção
					de abuso e funcionamento adequado dos serviços.
				</li>
			</ul>
			<p>
				Quando o tratamento depender de consentimento, este poderá ser retirado a qualquer momento. A
				retirada do consentimento não afeta a legalidade do tratamento realizado anteriormente.
			</p>
		</section>

		<!-- 5 -->
		<section id="fotografias" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">05 —</span> Fotografias</h2>
			<p>
				As fotografias podem conter pessoas identificáveis e, dependendo do contexto, podem constituir
				dados pessoais.
			</p>
			<p>
				As fotografias fornecidas no âmbito de um serviço são utilizadas para a finalidade para a qual
				foram fornecidas, incluindo edição, armazenamento, entrega e disponibilização através de álbuns
				privados.
			</p>
			<p>
				A publicação de fotografias na Galeria pública da Nostos será realizada apenas quando existir
				uma base legal adequada para essa utilização.
			</p>
			<p>
				A publicação de uma fotografia na Galeria pública não concede a terceiros qualquer direito de
				utilização ou reprodução da mesma.
			</p>
		</section>

		<!-- 6 -->
		<section id="claim" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">06 —</span> Claim</h2>
			<p>
				Quando utilizas a funcionalidade Claim e envias uma fotografia para procurar imagens
				visualmente semelhantes no arquivo da Nostos, a fotografia enviada pode ser processada para
				realizar essa pesquisa.
			</p>
			<p>A Nostos informará, no momento do envio, como a fotografia será tratada, incluindo:</p>
			<ul>
				<li>Se será armazenada</li>
				<li>Durante quanto tempo será mantida</li>
				<li>Para que finalidade será utilizada</li>
				<li>Se será eliminada após o processamento</li>
			</ul>
			<p class="pp-note">
				O comportamento definitivo desta funcionalidade será refletido nesta política antes da sua
				disponibilização pública.
			</p>
		</section>

		<!-- 7 -->
		<section id="analytics" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">07 —</span> Analytics</h2>
			<p>A Nostos pode utilizar métricas internas para compreender como o website é utilizado.</p>
			<p>As métricas podem incluir:</p>
			<ul>
				<li>Visitantes</li>
				<li>Visitas</li>
				<li>Visualizações de páginas</li>
				<li>Visualizações de fotografias</li>
				<li>Utilização da Galeria</li>
				<li>Pesquisas Claim</li>
				<li>Pedidos de serviço iniciados e concluídos</li>
			</ul>
			<p>
				Quando possível, serão utilizados identificadores pseudonimizados ou dados agregados em vez de
				dados diretamente identificáveis.
			</p>
			<p>
				Os dados de analytics serão conservados apenas durante o período necessário para as finalidades
				definidas pela Nostos.
			</p>
		</section>

		<!-- 8 -->
		<section id="cookies" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">08 —</span> Cookies</h2>
			<p>
				O website pode utilizar cookies e tecnologias semelhantes necessários ao seu funcionamento,
				segurança e gestão de sessões.
			</p>
			<p>
				Cookies não essenciais, incluindo determinados cookies de análise ou outros mecanismos de
				rastreamento, serão utilizados de acordo com os requisitos legais aplicáveis e, quando
				necessário, apenas após obtenção do consentimento.
			</p>
			<p class="pp-note">
				Mais informações podem ser consultadas na nossa <a href="/politica-de-cookies"
					>Política de Cookies</a
				>.
			</p>
		</section>

		<!-- 9 -->
		<section id="partilha" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">09 —</span> Com quem partilhamos os dados</h2>
			<p>
				Os dados pessoais podem ser disponibilizados a prestadores de serviços que atuem em nome da
				Nostos quando isso seja necessário para fornecer os serviços.
			</p>
			<p>Podem incluir, dependendo da arquitetura final:</p>
			<ul>
				<li>Serviços de alojamento</li>
				<li>Armazenamento de ficheiros</li>
				<li>Processamento de pagamentos</li>
				<li>Serviços de email</li>
				<li>Serviços técnicos e de infraestrutura</li>
				<li>Ferramentas necessárias para segurança e funcionamento da plataforma</li>
			</ul>
			<p>Estes fornecedores apenas devem receber os dados necessários para a respetiva finalidade.</p>
			<p class="pp-note">
				Os fornecedores utilizados pela Nostos serão identificados nesta política quando a
				infraestrutura definitiva estiver estabelecida.
			</p>
		</section>

		<!-- 10 -->
		<section id="transferencias" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">10 —</span> Transferências internacionais</h2>
			<p>
				Quando os dados pessoais forem transferidos para fora do Espaço Económico Europeu, a Nostos
				adotará as medidas e garantias exigidas pelo RGPD.
			</p>
			<p class="pp-note">
				As transferências e respetivas garantias serão identificadas nesta política quando os
				fornecedores utilizados pela Nostos estiverem definidos.
			</p>
		</section>

		<!-- 11 -->
		<section id="seguranca" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">11 —</span> Segurança</h2>
			<p>
				A Nostos implementa medidas técnicas e organizativas destinadas a proteger os dados pessoais
				contra:
			</p>
			<ul>
				<li>Acesso não autorizado</li>
				<li>Alteração não autorizada</li>
				<li>Perda</li>
				<li>Destruição</li>
				<li>Divulgação indevida</li>
			</ul>
			<p>
				O acesso aos dados é limitado de acordo com as funções e necessidades dos membros autorizados
				da equipa.
			</p>
			<p>
				Os dados e ficheiros privados devem ser protegidos através de mecanismos adequados de
				autenticação, autorização e controlo de acesso.
			</p>
		</section>

		<!-- 12 -->
		<section id="conservacao" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">12 —</span> Conservação dos dados</h2>
			<p>
				Os dados pessoais não serão conservados durante mais tempo do que o necessário para as
				finalidades para as quais foram recolhidos, salvo quando exista uma obrigação legal ou outra
				base legítima que exija uma conservação superior.
			</p>
			<p>Os períodos de conservação são definidos de acordo com o tipo de informação e finalidade.</p>
			<p>Exemplos:</p>
			<ul>
				<li>
					<strong>Pedidos de serviço</strong> — enquanto forem necessários para gerir o pedido e a relação
					associada.
				</li>
				<li>
					<strong>Dados de clientes</strong> — enquanto forem necessários para a prestação dos serviços e
					respetivas obrigações.
				</li>
				<li>
					<strong>Registos de compras</strong> — durante o período necessário para cumprimento das obrigações
					legais e contabilísticas.
				</li>
				<li><strong>Analytics</strong> — durante o período definido para as respetivas métricas.</li>
				<li>
					<strong>Logs de segurança</strong> — durante o período necessário para segurança e investigação
					de incidentes.
				</li>
			</ul>
			<p class="pp-note">
				Os períodos concretos de retenção serão definidos e documentados pela Nostos antes da
				utilização em produção.
			</p>
		</section>

		<!-- 13 -->
		<section id="direitos" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">13 —</span> Os teus direitos</h2>
			<p>Nos termos do RGPD, podes ter direito a:</p>
			<ul>
				<li>Ser informado sobre o tratamento dos teus dados</li>
				<li>Aceder aos teus dados pessoais</li>
				<li>Corrigir dados incorretos ou incompletos</li>
				<li>Solicitar a eliminação dos teus dados</li>
				<li>Solicitar a limitação do tratamento</li>
				<li>Solicitar a portabilidade dos dados, quando aplicável</li>
				<li>Opor-te a determinados tratamentos</li>
				<li>Retirar o consentimento quando o tratamento se basear no consentimento</li>
			</ul>
			<p>Estes direitos podem estar sujeitos às limitações e exceções previstas na legislação aplicável.</p>
		</section>

		<!-- 14 -->
		<section id="exercer" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">14 —</span> Como exercer os teus direitos</h2>
			<p>
				Para exercer os teus direitos ou colocar uma questão relacionada com a proteção dos teus
				dados, envia um pedido para:
			</p>
			<p>
				<a href="mailto:hello@nostos.studio" class="pp-email">hello@nostos.studio</a>
			</p>
			<p>
				O pedido poderá exigir confirmação da identidade quando necessário para proteger os dados
				pessoais contra acesso indevido.
			</p>
			<p>
				A Nostos tratará os pedidos nos prazos previstos no RGPD. Em regra, os pedidos devem ser
				respondidos sem demora injustificada e, em princípio, no prazo de um mês.
			</p>
		</section>

