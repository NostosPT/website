			</h2>
			<p>
				Embora atualmente não sejam utilizados cookies, determinadas funcionalidades futuras poderão
				utilizar tecnologias semelhantes, como armazenamento local do navegador ou mecanismos de sessão.
			</p>
			<p>
				Caso essas tecnologias sejam introduzidas e sejam relevantes para a privacidade do utilizador,
				esta política será atualizada e, quando legalmente necessário, serão fornecidas as informações
				e opções de consentimento adequadas.
			</p>
		</section>

