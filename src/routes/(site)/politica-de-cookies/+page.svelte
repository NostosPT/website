		<section id="o-que-sao" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">01 —</span> O que são cookies</h2>
			<p>
				Cookies são pequenos ficheiros armazenados no dispositivo do utilizador quando este visita um
				website. Podem ser utilizados para garantir o funcionamento do website, guardar preferências,
				analisar utilização ou suportar determinadas funcionalidades.
			</p>
		</section>

		<section id="nao-utiliza" class="pp-section">
			<h2><span class="pp-num" aria-hidden="true">02 —</span> A Nostos não utiliza cookies atualmente</h2>
			<p>Atualmente, o website da <strong>Nostos</strong> não utiliza cookies.</p>
			<p>Não utilizamos cookies para:</p>
			<ul>
				<li>publicidade;</li>
				<li>rastreamento de utilizadores;</li>
				<li>análise de comportamento através de cookies;</li>
				<li>personalização publicitária;</li>
				<li>criação de perfis de utilizadores.</li>
			</ul>
			<p>A Nostos também não utiliza atualmente cookies de terceiros para estes fins.</p>

			<div class="pp-callout" role="note" aria-label="Destaque">
				<p>
					<strong>No trackers. No ad cookies.</strong> — Tal como indicado no rodapé do site, a Nostos
					mantém o website livre de rastreamento publicitário.
				</p>
			</div>
		</section>

		<section id="armazenamento" class="pp-section">
